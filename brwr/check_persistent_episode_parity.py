#!/usr/bin/env python3
"""Compare standalone versus persistent BRWR JSONL episodes.

Semantic strictness: all gameplay fields must match exactly. Object instance IDs
in the network projection are compared using a stable per-episode bijection,
since Object.get_instance_id() is process-specific in Godot. Pixel coordinates
of presentation-only *attack* feedback (origin/destination x/y) are exempt:
they derive from animated Node2D.global_position, not logical room positions.
Transient Godot object IDs embedded in hand:<ID> candidate tokens also use
a stable episode-wide bijection; candidate metadata, order and choices remain strict.

Does not modify either JSONL, game source, or model. Python standard lib only.
"""
from itertools import zip_longest
from pathlib import Path
import json
import math
import re
import sys

# Deliberately narrow allowlist. These values originate from
# NetworkProjectionScript.build(...): get_instance_id() on QuestState and
# EvocationState objects. All other fields, including IDs with gameplay
# meaning, remain subject to exact comparison.
_OBJECT_ID_PATH = re.compile(
    r'^\$\.observation\.players\[\d+\]\.(?:active_quests|completed_quests|evocations)\[\d+\]\.instance$'
)

# Hand-card selection tokens in legal candidates embed a per-process Godot
# Object.get_instance_id() value. They are NOT portable card identifiers.
# Compare the token prefix exactly, and the suffix through the SAME stable
# per-episode one-to-one object ID mapping used for observation.instance.
# Do not relax payload tokens, other candidate token kinds, or card metadata.
_CANDIDATE_HAND_TOKEN_PATH = re.compile(
    r'^\$\.legal_candidates\[\d+\]\.(?:detail\.token|payload\.(?:selection|ai_select|token)|label)$'
)
_HAND_TOKEN = re.compile(r'^((?:Select )?hand:)([+-]?\d+)$')
_MIN_INT64 = -(1 << 63)
_MAX_INT64 = (1 << 63) - 1


# Visual-only feedback generated by Game.animate_model_attack() from
# Node2D.global_position. This is copied by NetworkProjection.build() into
# observation.feedback_events. It is NOT an input to NativePolicy.encode_action.
# Keep the allowlist EXACT: only x/y inside origin/destination of an attack event.
_ATTACK_FEEDBACK_EVENT_PATH = re.compile(r'^\$\.observation\.feedback_events\[\d+\]$')
_ATTACK_VISUAL_COORD_PATH = re.compile(
    r'^\$\.observation\.feedback_events\[\d+\]\.(?:origin|destination)\.(?:x|y)$'
)


def is_obj_id(path):
    return bool(_OBJECT_ID_PATH.fullmatch(path))


def shortened(value, limit=200):
    result = repr(value)
    return result if len(result) <= limit else result[:limit-3] + '...'


class Comparer:
    def __init__(self):
        self.a_to_b = {}
        self.b_to_a = {}
        self.object_id_occurrences = 0
        self.object_id_distinct = 0
        self.hand_token_occurrences = 0
        self.hand_token_differences = 0
        self.visual_coord_occurrences = 0
        self.visual_coord_differences = 0
        self.visual_examples = []

    def _compare_object_id(self, ia, ib, path):
        # Godot Object.get_instance_id() is signed int64; negative IDs are
        # legitimate. 0/-1 remain sentinels, not independently mappable IDs.
        if not (_MIN_INT64 <= ia <= _MAX_INT64 and _MIN_INT64 <= ib <= _MAX_INT64):
            return (path, f'object identity outside int64: ref={ia} persistent={ib}')
        if ia in (0, -1) or ib in (0, -1):
            return None if ia == ib else (path, f'null/sentinel identity differs: ref={ia} persistent={ib}')
        prior_b = self.a_to_b.get(ia)
        prior_a = self.b_to_a.get(ib)
        if (prior_b is not None and prior_b != ib) or (prior_a is not None and prior_a != ia):
            return (path, f'object identity mapping inconsistent: ref={ia} persistent={ib} '
                          f'existing_ref_to_persistent={prior_b} existing_persistent_to_ref={prior_a}')
        if prior_b is None:
            self.a_to_b[ia] = ib
            self.b_to_a[ib] = ia
            self.object_id_distinct += 1
        return None

    def first_difference(self, a, b, path='$', map_object_ids=True, attack_feedback=False):
        if type(a) is dict and type(b) is dict:
            if a.keys() != b.keys():
                missing_b = sorted(set(a) - set(b))
                missing_a = sorted(set(b) - set(a))
                return (path, f'key differences: ref_only={missing_b!r} persistent_only={missing_a!r}')
            # Only enter visual-exemption mode for an event where BOTH copies
            # explicitly agree that the event is an attack. Other events and
            # any different kind/serial/attacker/evocation data remain strict.
            is_attack_event = bool(_ATTACK_FEEDBACK_EVENT_PATH.fullmatch(path)) and a.get('kind') == b.get('kind') == 'attack'
            for k in sorted(a):
                child = self.first_difference(a[k], b[k], f'{path}.{k}', map_object_ids, is_attack_event or attack_feedback)
                if child is not None:
                    return child
            return None
        if type(a) is list and type(b) is list:
            if len(a) != len(b):
                return (path, f'lengths: reference={len(a)} persistent={len(b)}')
            for i, (x, y) in enumerate(zip(a, b)):
                child = self.first_difference(x, y, f'{path}[{i}]', map_object_ids, attack_feedback)
                if child is not None:
                    return child
            return None
        if map_object_ids and attack_feedback and _ATTACK_VISUAL_COORD_PATH.fullmatch(path):
            self.visual_coord_occurrences += 1
            # Only finite numerical positions may differ, not nulls,
            # malformed point objects, Booleans or NaNs.
            if (type(a) not in (float, int) or type(b) not in (float, int)
                    or not math.isfinite(a) or not math.isfinite(b)):
                return (path, f'invalid attack visual coordinate: ref={shortened(a)} persistent={shortened(b)}')
            if a != b:
                self.visual_coord_differences += 1
                if len(self.visual_examples) < 3:
                    self.visual_examples.append((path, a, b))
            return None
        if map_object_ids and _CANDIDATE_HAND_TOKEN_PATH.fullmatch(path):
            # Bridge._enumerate/_stage_candidates may replicate the *same*
            # hand token in detail, payload, and synthesized label. Only these
            # explicit candidate fields are eligible; other string differences
            # still fail. Different token prefixes must always fail.
            if isinstance(a, str) and isinstance(b, str):
                ma, mb = _HAND_TOKEN.fullmatch(a), _HAND_TOKEN.fullmatch(b)
                if ma is not None or mb is not None:
                    if ma is None or mb is None:
                        return (path, f'hand token format differs: ref={shortened(a)} persistent={shortened(b)}')
                    self.hand_token_occurrences += 1
                    if ma.group(1) != mb.group(1):
                        return (path, f'hand token prefix differs: ref={shortened(a)} persistent={shortened(b)}')
                    if ma.group(1).startswith('Select ') and not path.endswith('.label'):
                        return (path, 'synthesized label prefix in non-label hand token')
                    ia, ib = int(ma.group(2)), int(mb.group(2))
                    result = self._compare_object_id(ia, ib, path)
                    if result is not None:
                        return result
                    if a != b:
                        self.hand_token_differences += 1
                    return None
        if map_object_ids and is_obj_id(path):
            self.object_id_occurrences += 1
            if not isinstance(a, (int, float)) or isinstance(a, bool) or not isinstance(b, (int, float)) or isinstance(b, bool):
                return (path, f'non-numeric object identity: ref={shortened(a)} persistent={shortened(b)}')
            if int(a) != a or int(b) != b:
                return (path, f'non-integral object identity: ref={shortened(a)} persistent={shortened(b)}')
            return self._compare_object_id(int(a), int(b), path)
        # Int/float equivalence follows parsed JSON value semantics.
        if a != b:
            return (path, f'ref={shortened(a)} persistent={shortened(b)}')
        return None


def compare_files(a_path, b_path, stop_first=True):
    comparer = Comparer()
    count = starts = ends = transitions = 0
    raw_first = None
    ref_end = batch_end = None
    with Path(a_path).open('r', encoding='utf-8-sig') as fa, Path(b_path).open('r', encoding='utf-8-sig') as fb:
        for n, (left, right) in enumerate(zip_longest(fa, fb), 1):
            if left is None or right is None:
                return False, f'line {n}: different number of records', comparer, raw_first, (count, transitions, ref_end, batch_end)
            try:
                a = json.loads(left)
                b = json.loads(right)
            except (ValueError, TypeError) as exc:
                return False, f'line {n}: invalid JSON ({exc})', comparer, raw_first, (count, transitions, ref_end, batch_end)
            if a != b and raw_first is None:
                diagnostic = Comparer().first_difference(a, b, map_object_ids=False)
                raw_first = (n, diagnostic)
            mismatch = comparer.first_difference(a, b)
            if mismatch is not None:
                return False, f'line {n}: {mismatch[0]}: {mismatch[1]}', comparer, raw_first, (count, transitions, ref_end, batch_end)
            typ = a.get('record_type')
            starts += typ == 'episode_start'
            ends += typ == 'episode_end'
            transitions += typ == 'transition'
            count += 1
            if typ == 'episode_end':
                ref_end = a
                batch_end = b
    if starts != 1 or ends != 1 or transitions < 1 or count != transitions + 2:
        return False, f'invalid record counts start={starts} transition={transitions} end={ends}', comparer, raw_first, (count, transitions, ref_end, batch_end)
    return True, '', comparer, raw_first, (count, transitions, ref_end, batch_end)


def main():
    if len(sys.argv) != 3:
        sys.exit('Usage: python check_persistent_episode_parity.py reference.jsonl persistent.jsonl')
    a_path, b_path = map(Path, sys.argv[1:])
    if not a_path.is_file() or not b_path.is_file():
        sys.exit('PERSISTENT_SEMANTIC_PARITY_FAIL: missing reference or persistent JSONL')
    passed, detail, comp, raw, (n, decisions, ref_end, batch_end) = compare_files(a_path, b_path)
    if raw is not None:
        print(f'PERSISTENT_RAW_FIRST_DIFF line={raw[0]} path={raw[1][0]} {raw[1][1]}')
    if not passed:
        sys.exit('PERSISTENT_SEMANTIC_PARITY_FAIL: ' + detail)
    print(f'PERSISTENT_SEMANTIC_PARITY_OK records={n} decisions={decisions} '
          f'object_id_occurrences={comp.object_id_occurrences} '
          f'object_ids_mapped={comp.object_id_distinct} '
          f'hand_tokens_checked={comp.hand_token_occurrences} '
          f'hand_token_id_differences={comp.hand_token_differences} '
          f'attack_visual_coords_checked={comp.visual_coord_occurrences} '
          f'attack_visual_coord_differences={comp.visual_coord_differences} '
          'all_nonvolatile_fields_equal=1')
    for path, ref_value, batch_value in comp.visual_examples:
        print(f'PERSISTENT_ATTACK_VISUAL_DIFF path={path} ref={ref_value} persistent={batch_value}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
